/**
 * Runs the hijacked-agent benchmark (scripts/hijack-sim.ts) and the injection-detection recall
 * figures, and writes docs/benchmark.md. Usage: pnpm bench:hijack [attemptsPerFamily] (default 1000).
 * Deterministic for a given count: re-running it must not change the file.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { detectPromptInjection } from "@qm/trustrail";
import { BENIGN_PRODUCT_TEXT } from "../tests/adversarial/fixtures/benign-products";
import { FRESH_ATTACKS_ROUND2, FRESH_ATTACKS_ROUND3, HELDOUT_ATTACKS } from "../tests/adversarial/fixtures/heldout-attacks";
import { runBenchmark, type FamilyResult } from "./hijack-sim";

const per = Number(process.argv[2] ?? 1000);
if (!Number.isSafeInteger(per) || per < 1) throw new Error("attempts per family must be a positive integer");
const r = runBenchmark(per);

const fmt = (n: number) => n.toLocaleString("en-US");
const pct = (a: number, b: number) => `${((100 * a) / b).toFixed(1)}%`;
const top = (f: FamilyResult) =>
  Object.entries(f.codes)
    .sort((a, b) => b[1] - a[1])
    .filter(([, n]) => n >= f.attempts)
    .map(([c]) => `\`${c}\``)
    .join(", ");
const rows = (fs: FamilyResult[]) =>
  fs.map((f) => `| ${f.goal} | ${fmt(f.attempts)} | ${fmt(f.blocked)} | ${fmt(f.review)} | **${fmt(f.allowed)}** | ${top(f)} |`).join("\n");

const hostile = [...r.proposal, ...r.checkout].reduce((s, f) => s + f.attempts, 0);
const sentToOwner = r.proposal.reduce((s, f) => s + f.review, 0);
const recall = (set: [string, string][]) => {
  const v = set.map(([, t]) => detectPromptInjection(t));
  return { n: set.length, q: v.filter((x) => x.quarantine).length, f: v.filter((x) => x.suspicious).length };
};
const held = recall(HELDOUT_ATTACKS);
const r2 = recall(FRESH_ATTACKS_ROUND2);
const r3 = recall(FRESH_ATTACKS_ROUND3);
const benignQ = BENIGN_PRODUCT_TEXT.filter((t) => detectPromptInjection(t).quarantine).length;

const md = `# Benchmark: what a hijacked agent can do

Generated by \`pnpm bench:hijack ${per}\` from [scripts/hijack-sim.ts](../scripts/hijack-sim.ts) (seed ${r.seed}; deterministic).
Checked on every CI run at a smaller size by [tests/adversarial/hijacked-agent.test.ts](../tests/adversarial/hijacked-agent.test.ts).

## Headline

**${fmt(hostile)} hostile attempts from a fully hijacked agent; ${r.escapes} moved money outside the owner's Spend Mandate.**
${fmt(hostile - sentToOwner)} were refused outright; ${fmt(sentToOwner)} (buying more than the forecast needs) were held for the owner,
because buying ahead can be legitimate. Controls: ${fmt(r.controls.honestAllowed)} of ${fmt(r.controls.honestProposals)} honest
proposals allowed, ${fmt(r.controls.honestCaptured)} of ${fmt(r.controls.honestCheckouts)} untouched checkouts captured, so the gates
are not simply refusing everything.

## The assumption

Prompt injection is assumed to **succeed completely**: the attacker writes the agent's proposal and controls everything the agent
can reach. Detection is not part of this benchmark at all. What is tested is the code the agent cannot change: the deterministic
policy (\`evaluatePolicy\`, re-run on approval, which refuses any BLOCK even for the owner) and the pre-capture gate
(\`verifyCertificate\` + \`guardCapture\`, the only path to PayPal's capture call). Each attempt is a random variant of one attacker goal;
a family counts as caught only when the rule meant for it fires on every attempt (the last column).

## Stage A: hostile proposals (${fmt(r.proposal.reduce((s, f) => s + f.attempts, 0))} attempts)

| Attacker goal | Attempts | Blocked | Sent to owner | Allowed | Rule that fired on every attempt |
| --- | ---: | ---: | ---: | ---: | --- |
${rows(r.proposal)}

## Stage B: attacks on an approved checkout (${fmt(r.checkout.reduce((s, f) => s + f.attempts, 0))} attempts)

Each starts from an order the owner really approved and TrustRail really signed (Ed25519), then changes one thing before capture.

| Attacker goal | Attempts | Blocked | Sent to owner | Captured | Check that fired on every attempt |
| --- | ---: | ---: | ---: | ---: | --- |
${rows(r.checkout)}

## Injection detection, reported separately

Detection is a second line that keeps poisoned text away from the model; the results above do not depend on it.

| Corpus | Attacks | Quarantined | Flagged |
| --- | ---: | ---: | ---: |
| Held-out corpus (written before the rules) | ${held.n} | ${pct(held.q, held.n)} | ${pct(held.f, held.n)} |
| Fresh round 2 (tuned against once) | ${r2.n} | ${pct(r2.q, r2.n)} | ${pct(r2.f, r2.n)} |
| Fresh round 3 (never tuned against) | ${r3.n} | ${pct(r3.q, r3.n)} | ${pct(r3.f, r3.n)} |

False quarantines on ${BENIGN_PRODUCT_TEXT.length} benign product descriptions: ${benignQ}. Round 3 is the honest estimate for new
phrasings: roughly half are caught by detection, which is exactly why money movement is decided by policy and not by detection.

## Limits

- This exercises TrustRail's pure decision code with synthetic carts, not the HTTP stack or PayPal itself (the integration suite and
  the Playwright journeys cover those paths, with a fake PayPal).
- A purchase the mandate allows is allowed: TrustRail bounds what a hijacked agent can spend, it does not judge taste. Keep the
  mandate tight (approved suppliers, limits, human approval) for that bound to be small.
- The owner can still approve something they should not; held orders show the reasons first.
`;

const out = fileURLToPath(new URL("../docs/benchmark.md", import.meta.url));
// formatted like the rest of the repo, so `pnpm format:check` passes on a fresh run
writeFileSync(out, await format(md, { ...(await resolveConfig(out)), filepath: out }));
console.info(`docs/benchmark.md: ${hostile} hostile attempts, ${r.escapes} escapes, ${sentToOwner} sent to owner`);
