from enum import Enum
from typing import Annotated, TypeAlias

from ...core import open_enum_validator


class ViolationCode(str, Enum):
    """Machine-readable TrustRail policy violation."""

    MANDATE_INACTIVE = "MANDATE_INACTIVE"
    EMPTY_CART = "EMPTY_CART"
    CURRENCY_MISMATCH = "CURRENCY_MISMATCH"
    SUPPLIER_NOT_APPROVED = "SUPPLIER_NOT_APPROVED"
    SUPPLIER_INACTIVE = "SUPPLIER_INACTIVE"
    CATEGORY_NOT_ALLOWED = "CATEGORY_NOT_ALLOWED"
    UNAUTHORIZED_LINE_ITEM = "UNAUTHORIZED_LINE_ITEM"
    PRICE_MISMATCH = "PRICE_MISMATCH"
    CART_ARITHMETIC_INVALID = "CART_ARITHMETIC_INVALID"
    PER_ORDER_LIMIT_EXCEEDED = "PER_ORDER_LIMIT_EXCEEDED"
    WEEKLY_BUDGET_EXCEEDED = "WEEKLY_BUDGET_EXCEEDED"
    REQUEST_BUDGET_EXCEEDED = "REQUEST_BUDGET_EXCEEDED"
    MARKET_PRICE_PREMIUM_EXCEEDED = "MARKET_PRICE_PREMIUM_EXCEEDED"
    MARKET_REFERENCE_UNAVAILABLE = "MARKET_REFERENCE_UNAVAILABLE"
    DUPLICATE_ORDER = "DUPLICATE_ORDER"
    SUBSCRIPTION_NOT_ALLOWED = "SUBSCRIPTION_NOT_ALLOWED"
    QUARANTINED_SOURCE = "QUARANTINED_SOURCE"
    QUANTITY_EXCEEDS_NEED = "QUANTITY_EXCEEDS_NEED"
    POLICY_INPUT_INVALID = "POLICY_INPUT_INVALID"

    __str__ = str.__str__


ViolationCodeOrStr: TypeAlias = Annotated[ViolationCode | str, open_enum_validator(ViolationCode)]
